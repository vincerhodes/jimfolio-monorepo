async function fetchSvg(id, useProxy) {
  const url = `https://api.iconify.design/${id.replace(":", "/")}.svg`;
  const res = await fetch(url, useProxy ? { agent: undefined } : {});
  if (!res.ok) return null;
  const text = await res.text();
  return text.startsWith("<svg") ? text : null;
}

// Minimal http(s)-get via proxy (fetch in Node 20 supports agent poorly) — use curl fallback.
async function fetchViaCurl(id) {
  const { execFile } = await import("node:child_process");
  const url = `https://api.iconify.design/${id.replace(":", "/")}.svg`;
  return new Promise((resolve) => {
    execFile(
      "curl",
      ["-s", "-x", "http://127.0.0.1:7897", "--max-time", "20", url],
      (err, stdout) => {
        if (err || !stdout.startsWith("<svg")) return resolve(null);
        resolve(stdout);
      }
    );
  });
}

const svgs = {};
const failed = [];

for (const id of ICON_IDS) {
  let svg = await fetchSvg(id);
  if (!svg) svg = await fetchViaCurl(id);
  if (svg) {
    svgs[id] = svg;
    console.log(`ok   ${id}`);
  } else {
    failed.push(id);
    console.error(`FAIL ${id}`);
  }
}

const entries = Object.entries(svgs)
  .map(([id, svg]) => `  ${JSON.stringify(id)}: ${JSON.stringify(svg)}`)
  .join(",\n");

const out =
  `// Generated by scripts/fetch-icons.mjs — do not edit by hand.\n` +
  `// Raw SVG markup from the Iconify API (allsvgicons / iconify).\n\n` +
  `export const iconSvgs: Record<string, string> = {\n${entries}\n};\n`;

await writeFile(path.join(appDir, "lib", "icon-svgs.ts"), out);
console.log(`\nwrote lib/icon-svgs.ts (${Object.keys(svgs).length}/${ICON_IDS.length} icons)`);
if (failed.length) {
  console.error(`failed: ${failed.join(", ")}`);
  process.exitCode = 1;
}
